import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import ts from 'typescript';
const context = { exports: {} };
vm.runInNewContext(ts.transpileModule(readFileSync(new URL('../src/features/courses/catalogPagination.ts', import.meta.url), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, context);
const page = context.exports.catalogPage;
const fixtureContext = { exports: {} };
vm.runInNewContext(ts.transpileModule(readFileSync(new URL('./fixtures/catalog.ts', import.meta.url), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, fixtureContext);
const fixture = fixtureContext.exports.catalogFixture;
assert.equal(page(fixture, '', false, 1).visibleCourses.length, 6);
assert.equal(page(fixture, '', false, 2).visibleCourses[0].id, '6');
assert.equal(page(fixture, '', false, 3).visibleCourses.length, 2);
assert.equal(page(fixture, '', false, 99).currentPage, 3);
const searched = page(fixture, 'unique', false, 3);
assert.equal(searched.currentPage, 1); assert.equal(searched.visibleCourses[0].id, '13');
const filtered = page(fixture, '', true, 3);
assert.equal(filtered.currentPage, 2); assert.equal(filtered.visibleCourses.length, 1);
const empty = page(fixture, 'no match', false, 3);
assert.equal(empty.currentPage, 1); assert.equal(empty.totalPages, 0); assert.equal(empty.visibleCourses.length, 0);
assert.equal(page([], '', false, 1).visibleCourses.length, 0);
console.log('Catalog fixture checks passed: multiple pages, last page, empty, search/filter from later pages.');
